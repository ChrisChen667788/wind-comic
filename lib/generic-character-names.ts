/**
 * lib/generic-character-names (v12.373) —— 通用占位名,不该参与跨项目复用。
 *
 * 病根:v12.369 我把 Character Bible 回填好之后,跨项目复用终于能命中了 ——
 * **但也把「主角」「伙伴」这类占位名一起命中了**。实测 owner 的库里:
 *   主角 79 个项目 · 伙伴 78 个项目 · 一只橘猫 13 个
 *   而真实角色名(李长安/柳如烟/悠悠)都只有 1~3 个。
 *
 * 界面会提示「📚 已找到「主角」—— **79 个历史项目用过** —— 一键复用」,
 * 而那 79 个项目彼此毫无关系。**用户一点,就把无关项目的角色图套了进来** ——
 * 这比「找不到」更糟:找不到只是没帮上忙,套错是主动帮了倒忙。
 *
 * 判定不靠「引用次数多」这种间接信号(真·系列主角也可能出现在很多项目里),
 * 而是**这个名字本身是不是角色身份** —— 「主角」是**角色定位**,不是名字。
 */

/** 角色定位词 / 占位名 —— 它们描述「这个人在故事里的功能」,不是「这个人是谁」。 */
const GENERIC_NAMES = new Set([
  '主角', '男主', '女主', '男主角', '女主角', '主人公', '主人翁',
  '配角', '伙伴', '同伴', '朋友', '搭档', '助手',
  '反派', 'боss', '大反派', '对手', '敌人',
  '路人', '群演', '龙套', '旁白', '解说', 'npc',
  '男人', '女人', '男孩', '女孩', '老人', '孩子', '小孩',
  '顾客', '店员', '服务员', '司机', '警察', '医生', '护士', '老师', '学生',
  'protagonist', 'hero', 'heroine', 'villain', 'sidekick', 'narrator',
  'main character', 'supporting', 'extra', 'npc',
]);

/**
 * 是不是通用占位名(不该跨项目复用)。
 *
 * 判定**只看名字本身**,不看引用次数 —— 真·系列主角(如「李长安」出现在多部)
 * 引用次数也会很高,拿次数当信号会把它一起误杀。
 */
export function isGenericCharacterName(name: string | null | undefined): boolean {
  const n = String(name || '').trim().toLowerCase();
  if (!n) return true;                       // 空名字更不该复用
  if (GENERIC_NAMES.has(n)) return true;
  // 「男主2」「配角A」这类带编号的占位名
  if (/^(主角|男主|女主|配角|反派|路人|伙伴|同伴)[\s\-_]?[0-9a-z]{0,2}$/i.test(n)) return true;
  return false;
}

/** 供测试与排查用 —— 不导出可变引用。 */
export const GENERIC_NAME_COUNT = GENERIC_NAMES.size;
